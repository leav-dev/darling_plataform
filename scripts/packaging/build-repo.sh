#!/usr/bin/env bash
# Build a local apt repository from the .deb files in dist/, and verify one.
#
# Usage:
#   scripts/packaging/build-repo.sh                          # unsigned repo in dist/repo
#   scripts/packaging/build-repo.sh --sign KEYID             # sign Release.gpg with KEYID
#   scripts/packaging/build-repo.sh --out /tmp/repo          # write the repository elsewhere
#   scripts/packaging/build-repo.sh --check --out /tmp/repo   # verify an existing repo, change nothing
#
# The repository is a single-component local archive:
#   <out>/pool/                                     the .deb files
#   <out>/dists/local/Release                       archive metadata (+ Release.gpg when signed)
#   <out>/dists/local/main/binary-<arch>/Packages    generated by dpkg-scanpackages
#   <out>/dists/local/main/binary-<arch>/Packages.gz
#
# Nothing is written outside <out> (default: <repo>/dist/repo), /etc is never
# touched and nothing is installed. An unsigned repository is only useful on the
# machine that built it: it must not be published.

set -euo pipefail

readonly repo_root="$(cd "$(dirname "$0")/../.." && pwd)"
readonly origin="darling-platform"
readonly label="Darling Platform"
readonly suite="local"
readonly codename="local"
readonly component="main"

umask 0022

usage() {
    sed -n '2,18p' "$0" | sed 's/^# \{0,1\}//'
}

fail() {
    printf 'error: %s\n' "$*" >&2
    exit 1
}

note() {
    printf '    %s\n' "$*"
}

step() {
    printf '\n==> %s\n' "$*"
}

# Removes a path, but only when it is strictly inside the output directory.
remove_tree() {
    local path="$1"
    case "$path" in
    "" | "/") fail "refusing to remove '$path'" ;;
    "${out_dir}/"?*) ;;
    *) fail "refusing to remove '$path': it is outside '$out_dir'" ;;
    esac
    rm -rf -- "$path"
}

# Prints "<algorithm>:" plus one " <sum> <size> <path>" line per index file.
release_checksum_block() {
    local algorithm="$1" hasher="$2" relative sum size
    printf '%s:\n' "$algorithm"
    for relative in "${index_files[@]}"; do
        sum="$("$hasher" "${dist_dir}/${relative}" | cut -d' ' -f1)"
        size="$(stat -c %s "${dist_dir}/${relative}")"
        printf ' %s %s %s\n' "$sum" "$size" "$relative"
    done
}

deb_source_dir="${repo_root}/dist"
out_dir="${repo_root}/dist/repo"
key_id=""
check_mode=0

while [ "$#" -gt 0 ]; do
    case "$1" in
    --sign)
        [ "$#" -ge 2 ] || fail "--sign needs a GPG key id"
        key_id="$2"
        shift 2
        ;;
    --sign=*)
        key_id="${1#*=}"
        shift
        ;;
    --out)
        [ "$#" -ge 2 ] || fail "--out needs a directory"
        out_dir="$2"
        shift 2
        ;;
    --out=*)
        out_dir="${1#*=}"
        shift
        ;;
    --check)
        check_mode=1
        shift
        ;;
    -h | --help)
        usage
        exit 0
        ;;
    *)
        fail "unknown argument '$1' (see --help)"
        ;;
    esac
done

for tool in dpkg dpkg-deb dpkg-scanpackages gzip sha256sum; do
    command -v "$tool" >/dev/null 2>&1 || fail "$tool is required to build the repository"
done

[ -n "$key_id" ] && [ "$check_mode" -eq 1 ] && fail "--check verifies an existing repository and never signs; drop --sign or drop --check"

if [ "$check_mode" -eq 1 ]; then
    [ -d "$out_dir" ] || fail "no repository at $out_dir: the directory does not exist"
else
    mkdir -p "$out_dir"
fi
out_dir="$(cd "$out_dir" && pwd)"

readonly arch="$(dpkg --print-architecture)"
readonly pool_dir="${out_dir}/pool"
readonly dist_dir="${out_dir}/dists/${suite}"
readonly index_dir="${dist_dir}/${component}/binary-${arch}"
readonly packages_file="${index_dir}/Packages"
readonly packages_gz="${index_dir}/Packages.gz"
readonly release_file="${dist_dir}/Release"
readonly release_sig="${dist_dir}/Release.gpg"
readonly index_files=("${component}/binary-${arch}/Packages" "${component}/binary-${arch}/Packages.gz")

# --- verification mode ------------------------------------------------------
if [ "$check_mode" -eq 1 ]; then
    [ -d "$out_dir" ] || fail "no repository at $out_dir"
    [ -f "$packages_file" ] || fail "no repository at $out_dir: $packages_file is missing"
    [ -f "$packages_gz" ] || fail "no repository at $out_dir: $packages_gz is missing"
    [ -f "$release_file" ] || fail "no repository at $out_dir: $release_file is missing"
    [ -d "$pool_dir" ] || fail "no repository at $out_dir: $pool_dir is missing"

    step "checking the gzip index"
    gzip -dc "$packages_gz" | cmp -s - "$packages_file" ||
        fail "$packages_gz does not decompress to the same text as $packages_file; rebuild the repository"
    note "ok $packages_gz == $packages_file"

    step "checking every Packages entry against the pool"
    entries=0
    failures=0
    while read -r relative expected_sha expected_size; do
        [ -n "$relative" ] || continue
        entries=$((entries + 1))
        case "$relative" in
        "${component}/"* | pool/*)
            ;;
        *)
            printf 'error: %s lists an entry outside the pool: %s\n' "$packages_file" "$relative" >&2
            failures=$((failures + 1))
            continue
            ;;
        esac
        artefact="${out_dir}/${relative}"
        if [ ! -f "$artefact" ]; then
            printf 'error: %s is listed in Packages but missing from the pool\n' "$artefact" >&2
            failures=$((failures + 1))
            continue
        fi
        actual_sha="$(sha256sum "$artefact" | cut -d' ' -f1)"
        actual_size="$(stat -c %s "$artefact")"
        if [ "$actual_sha" != "$expected_sha" ] || [ "$actual_size" != "$expected_size" ]; then
            printf 'error: %s does not match Packages (expected sha256 %s / %s bytes, got %s / %s bytes)\n' \
                "$artefact" "$expected_sha" "$expected_size" "$actual_sha" "$actual_size" >&2
            failures=$((failures + 1))
            continue
        fi
        note "ok $relative (sha256 ${actual_sha:0:16}..., ${actual_size} bytes)"
    done < <(
        awk '
            /^Filename: / { filename = $2 }
            /^SHA256: /   { sha = $2 }
            /^Size: /     { size = $2 }
            /^$/          { if (filename != "") print filename, sha, size; filename = ""; sha = ""; size = "" }
            END           { if (filename != "") print filename, sha, size }
        ' "$packages_file"
    )

    step "checking every pool artefact is indexed"
    for artefact in "$pool_dir"/*.deb; do
        [ -e "$artefact" ] || continue
        base="${artefact##*/}"
        if ! grep -qx "Filename: pool/${base}" "$packages_file"; then
            printf 'error: %s is in the pool but not indexed in Packages\n' "$artefact" >&2
            failures=$((failures + 1))
        fi
    done
    note "ok every .deb in the pool has a Packages entry"

    step "checking the Release checksums"
    for relative in "${index_files[@]}"; do
        expected="$(sha256sum "${dist_dir}/${relative}" | cut -d' ' -f1)"
        recorded="$(awk -v wanted="$relative" '
            /^SHA256:/ { in_block = 1; next }
            /^[^ ]/    { in_block = 0 }
            in_block && $3 == wanted { print $1; exit }
        ' "$release_file")"
        if [ -z "$recorded" ]; then
            printf 'error: %s does not list a SHA256 checksum for %s\n' "$release_file" "$relative" >&2
            failures=$((failures + 1))
            continue
        fi
        if [ "$recorded" != "$expected" ]; then
            printf 'error: %s records sha256 %s for %s but the file has %s\n' \
                "$release_file" "$recorded" "$relative" "$expected" >&2
            failures=$((failures + 1))
            continue
        fi
        note "ok $relative matches $release_file"
    done

    if [ "$failures" -gt 0 ]; then
        fail "$failures drift(s) found in $out_dir; rebuild the repository with scripts/packaging/build-repo.sh"
    fi

    step "repository is consistent"
    note "$entries package entries verified in $out_dir"
    exit 0
fi

# --- build mode -------------------------------------------------------------
shopt -s nullglob
debs=("$deb_source_dir"/*.deb)
shopt -u nullglob

[ "${#debs[@]}" -gt 0 ] || fail "no .deb in $deb_source_dir; run scripts/packaging/build-deb.sh first"

# The archive is single-architecture, so every package must agree with the host
# architecture this repository is generated for.
for deb in "${debs[@]}"; do
    deb_arch="$(dpkg-deb --field "$deb" Architecture)"
    [ "$deb_arch" = "$arch" ] || fail "$deb is built for '$deb_arch' but this repository targets '$arch'"
done

step "copying ${#debs[@]} package(s) into $pool_dir"
remove_tree "$pool_dir"
install -d -m 0755 "$pool_dir" "$index_dir"
for deb in "${debs[@]}"; do
    install -m 0644 "$deb" "${pool_dir}/${deb##*/}"
    note "pool/${deb##*/}"
done

step "dpkg-scanpackages -> $packages_file"
(
    cd "$out_dir"
    LC_ALL=C dpkg-scanpackages --multiversion pool >"$packages_file"
)

step "gzip --best --no-name -> $packages_gz"
gzip --best --no-name -c "$packages_file" >"$packages_gz"
chmod 0644 "$packages_file" "$packages_gz"

# A fixed Date keeps the repository reproducible when SOURCE_DATE_EPOCH is set.
if [ -n "${SOURCE_DATE_EPOCH-}" ]; then
    release_date="$(LC_ALL=C date -u -d "@${SOURCE_DATE_EPOCH}" '+%a, %d %b %Y %H:%M:%S UTC')"
else
    release_date="$(LC_ALL=C date -u '+%a, %d %b %Y %H:%M:%S UTC')"
fi

step "writing $release_file"
{
    printf 'Origin: %s\n' "$origin"
    printf 'Label: %s\n' "$label"
    printf 'Suite: %s\n' "$suite"
    printf 'Codename: %s\n' "$codename"
    printf 'Architectures: %s\n' "$arch"
    printf 'Components: %s\n' "$component"
    printf 'Description: %s\n' "Local ${origin} apt repository"
    printf 'Date: %s\n' "$release_date"
    release_checksum_block MD5Sum md5sum
    release_checksum_block SHA256 sha256sum
} >"$release_file"
chmod 0644 "$release_file"

if [ -n "$key_id" ]; then
    step "signing $release_file with $key_id"
    command -v gpg >/dev/null 2>&1 ||
        fail "gpg is required by --sign: install gnupg, or build the repository without --sign (it will be unsigned and must not be published)"
    gpg --batch --list-secret-keys -- "$key_id" >/dev/null 2>&1 ||
        fail "gpg has no secret key '$key_id': import it with 'gpg --import <key>.asc', list your keys with 'gpg --list-secret-keys', or build the repository without --sign"
    gpg --batch --yes --armor --detach-sign -u "$key_id" --output "$release_sig" "$release_file"

    # apt verifies Release.gpg against a keyring, not against a detached
    # signature file, so the public key is exported next to the archive.
    keyring="${out_dir}/${origin}-archive-keyring.gpg"
    gpg --batch --export -- "$key_id" >"$keyring"
    chmod 0644 "$release_sig" "$keyring"
    note "Release.gpg: $release_sig"
    note "public key:  $keyring"
else
    printf '\n' >&2
    printf 'warning: this repository is UNSIGNED.\n' >&2
    printf '         apt cannot verify it, so it is only safe on the machine that built\n' >&2
    printf '         it. Do not publish it. Re-run with --sign KEYID to sign Release.\n' >&2
fi

step "done"
note "repository: $out_dir"
cat <<EOF

    Add this line to a file under /etc/apt/sources.list.d/ (this script never
    edits /etc):

EOF
if [ -n "$key_id" ]; then
    printf '      deb [signed-by=%s] file://%s %s %s\n\n' \
        "${out_dir}/${origin}-archive-keyring.gpg" "$out_dir" "$suite" "$component"
else
    printf '      deb [trusted=yes] file://%s %s %s\n\n' "$out_dir" "$suite" "$component"
    note "an unsigned repository needs trusted=yes; it must not be published"
    printf '\n'
fi
note "then: sudo apt-get update"
